var generatedAssets embed.FS

type Inspection struct {
	Image      *Image           `json:"image"`
	Assemblies []Assembly       `json:"assemblies"`
	Types      []TypeDefinition `json:"types"`
	Methods    []Method         `json:"methods"`
	Bodies     []*MethodBody    `json:"bodies"`
	Resources  []Resource       `json:"resources"`
}

func (im *Image) Inspect() (*Inspection, error) {
	out := &Inspection{Image: im}
	var e error
	out.Assemblies, e = im.Metadata.Assemblies()
	if e != nil {
		return nil, e
	}
	out.Types, e = im.Metadata.Types()
	if e != nil {
		return nil, e
	}
	out.Methods, e = im.Metadata.Methods()
	if e != nil {
		return nil, e
	}
	if strings.HasPrefix(im.Format, "PE") {
		for _, m := range out.Methods {
			b, e := im.MethodBody(m.Token)
			if e != nil {
				return nil, e
			}
			out.Bodies = append(out.Bodies, b)
		}
		out.Resources, e = im.Resources()
	}
	return out, e
}
func (im *Image) WriteJSON(w io.Writer) error {
	out, e := im.Inspect()
	if e != nil {
		return e
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(out)
}
func (im *Image) GenerateRust(output string) error { return GenerateRust(output) }

// WriteRustModule writes one dependency-free Rust module. The generated CIL
// library can install it as `pub mod dotnet;` and decode MethodBody.il directly.
func WriteRustModule(path string) error {
	var b bytes.Buffer
	b.WriteString("// Generated by go-mkasm; MIT license. See UPSTREAM-NOTICE.md.\n")
	b.WriteString("fn schema(t:usize)->Option<(&'static str,&'static [(&'static str,&'static str)])>{match t{\n")
	for i, s := range Schemas {
		if s == nil {
			continue
		}
		fmt.Fprintf(&b, "%d=>Some((%q,&[", i, s.Name)
		for _, c := range s.Columns {
			fmt.Fprintf(&b, "(%q,%q),", c.Name, c.Kind)
		}
		b.WriteString("])),\n")
	}
	b.WriteString("_=>None}}\nfn coded(k:&str)->Option<(u32,&'static [i32])>{match k{\n")
	keys := []string{}
	for k := range CodedIndices {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		c := CodedIndices[k]
		fmt.Fprintf(&b, "%q=>Some((%d,&[", k, c.Bits)
		for _, t := range c.Tables {
			fmt.Fprintf(&b, "%d,", t)
		}
		b.WriteString("])),\n")
	}
	b.WriteString("_=>None}}\n")
	r, e := generatedAssets.ReadFile("rust_runtime.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	r, e = generatedAssets.ReadFile("rust_edit.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	r, e = generatedAssets.ReadFile("rust_evaluation.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	r, e = generatedAssets.ReadFile("rust_blobs.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	r, e = generatedAssets.ReadFile("rust_reference.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	r, e = generatedAssets.ReadFile("rust_readytorun.rs")
	if e != nil {
		return e
	}
	b.Write(r)
	if e = os.MkdirAll(filepath.Dir(path), 0755); e != nil {
		return e
	}
	return os.WriteFile(path, b.Bytes(), 0644)
}
func GenerateRust(output string) (generationError error) {
	defer func() {
		if generationError == nil {
			generationError = objectapi.InstallRust(output)
		}
	}()

	if e := WriteRustModule(filepath.Join(output, "src/lib.rs")); e != nil {
		return e
	}
	if e := os.WriteFile(filepath.Join(output, "Cargo.toml"), []byte("[package]\nname = \"mkasm-dotnet\"\nversion = \"0.1.0\"\nedition = \"2021\"\nlicense = \"MIT\"\n\n[lib]\npath = \"src/lib.rs\"\n"), 0644); e != nil {
		return e
	}
	if e := codec.WriteLicense(output); e != nil {
		return e
	}
	if e := WriteRustNotice(output); e != nil {
		return e
	}
	return WriteRustTests(output, "mkasm_dotnet")
}

