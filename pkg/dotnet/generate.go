func rustString(s string) string {
	b, _ := json.Marshal(s)
	return strings.ReplaceAll(strings.ReplaceAll(string(b), "\\u003c", "<"), "\\u003e", ">")
}

// WriteRustNotice installs the specification notices alongside an embedded module.
func WriteRustNotice(output string) error {
	notice, e := generatedAssets.ReadFile("UPSTREAM-NOTICE.md")
	if e != nil {
		return e
	}
	if e = os.MkdirAll(output, 0755); e != nil {
		return e
	}
	return os.WriteFile(filepath.Join(output, "UPSTREAM-NOTICE.md"), notice, 0644)
}
